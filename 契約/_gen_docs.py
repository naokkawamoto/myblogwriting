HEADERS = ["業務フロー","No","機能","説明","PC","Tab","スマホ","見積","開発できない項目／コメント"]

def build_xlsx():
    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = "別紙1 開発項目一覧"

    title_font = Font(name="Yu Gothic", size=14, bold=True)
    head_font = Font(name="Yu Gothic", size=10, bold=True, color="FFFFFF")
    body_font = Font(name="Yu Gothic", size=10)
    head_fill = PatternFill("solid", fgColor="2F5496")
    grp_fill = PatternFill("solid", fgColor="D9E1F2")
    thin = Side(style="thin", color="BFBFBF")
    border = Border(left=thin, right=thin, top=thin, bottom=thin)
    wrap = Alignment(wrap_text=True, vertical="top")
    center = Alignment(horizontal="center", vertical="center")

    ws.merge_cells("A1:I1")
    c = ws["A1"]; c.value = "別紙1　開発項目一覧（リノベーション現調・設計・積算支援システム）　2025年2月11日"
    c.font = title_font

    r = 3
    for j, h in enumerate(HEADERS, start=1):
        cell = ws.cell(row=r, column=j, value=h)
        cell.font = head_font; cell.fill = head_fill; cell.border = border
        cell.alignment = center
    r += 1

    for row in ROWS:
        is_group_start = bool(row[1])  # Noがある=機能の先頭行
        for j, val in enumerate(row, start=1):
            cell = ws.cell(row=r, column=j, value=val)
            cell.font = body_font; cell.border = border
            if j in (1,2,5,6,7,8):
                cell.alignment = center
            else:
                cell.alignment = wrap
            if is_group_start and j == 1:
                cell.fill = grp_fill
        r += 1

    widths = [14,5,22,60,5,5,7,9,40]
    for i, w in enumerate(widths, start=1):
        ws.column_dimensions[get_column_letter(i)].width = w
    ws.freeze_panes = "A4"
    ws.sheet_view.showGridLines = False
    wb.save(OUT_XLSX)
    print("wrote", OUT_XLSX)

def add_clause(doc, title, body_lines):
    h = doc.add_paragraph()
    run = h.add_run(title); run.bold = True; run.font.size = Pt(12)
    for line in body_lines:
        doc.add_paragraph(line)

